export const translations: Record<Language, Record<string, string>> = {
  en: Object.fromEntries(Object.keys(hindi).map((key) => [key, key])),
  hi: hindi,
};

const textOriginals = new WeakMap<Text, string>();
const textTranslations = new WeakMap<Text, string>();
const attributeOriginals = new WeakMap<Element, Map<string, string>>();
const attributeTranslations = new WeakMap<Element, Map<string, string>>();
const translatableAttributes = ["placeholder", "aria-label", "title"];
const nonTranslatableTextTags = new Set(["SCRIPT", "STYLE", "NOSCRIPT", "INPUT", "TEXTAREA", "SELECT", "OPTION", "CODE", "PRE"]);

export function translateText(value: string, language: Language) {
  if (language === "en") return value;
  return Object.entries(translations.hi)
    .sort(([left], [right]) => right.length - left.length)
    .reduce((result, [english, hindiValue]) => result.split(english).join(hindiValue), value);
}

function translatePage(root: HTMLElement, language: Language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let current: Node | null;
  while ((current = walker.nextNode())) {
    const text = current as Text;
    if (!text.parentElement || nonTranslatableTextTags.has(text.parentElement.tagName) || text.parentElement.closest("[data-no-translate]")) continue;
    const currentValue = text.nodeValue ?? "";
    const previousTranslation = textTranslations.get(text);
    const original = !textOriginals.has(text) || (previousTranslation !== undefined && currentValue !== previousTranslation)
      ? currentValue
      : textOriginals.get(text) ?? currentValue;
    textOriginals.set(text, original);
    const translated = translateText(original, language);
    textTranslations.set(text, translated);
    if (text.nodeValue !== translated) text.nodeValue = translated;
  }

  root.querySelectorAll<HTMLElement>("*").forEach((element) => {
    for (const attribute of translatableAttributes) {
      const value = element.getAttribute(attribute);
      if (value === null) continue;
      let originals = attributeOriginals.get(element);
      if (!originals) {
        originals = new Map();
        attributeOriginals.set(element, originals);
      }
      let translatedValues = attributeTranslations.get(element);
      if (!translatedValues) {
        translatedValues = new Map();
        attributeTranslations.set(element, translatedValues);
      }
      const previousTranslation = translatedValues.get(attribute);
      const original = !originals.has(attribute) || (previousTranslation !== undefined && value !== previousTranslation)
        ? value
        : originals.get(attribute) ?? value;
      originals.set(attribute, original);
      const translated = translateText(original, language);
      translatedValues.set(attribute, translated);
      if (value !== translated) element.setAttribute(attribute, translated);
    }
  });
}

type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (value: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function getInitialLanguage(): Language {
  if (typeof window !== "undefined" && window.localStorage.getItem("ss-language") === "hi") return "hi";
  return "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);
  const setLanguage = (nextLanguage: Language) => {
    window.localStorage.setItem("ss-language", nextLanguage);
    setLanguageState(nextLanguage);
  };
  const value = useMemo(() => ({ language, setLanguage, t: (value: string) => translateText(value, language) }), [language]);

  return createElement(LanguageContext.Provider, { value }, children);
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}

export function LanguageSync({ children }: { children: ReactNode }) {
  const { language } = useLanguage();
  useEffect(() => {
    const root = document.getElementById("root");
    if (!root) return;
    const apply = () => translatePage(root, language);
    apply();
    const observer = new MutationObserver(apply);
    observer.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: translatableAttributes,
    });
    return () => observer.disconnect();
  }, [language]);
  return createElement(Fragment, null, children);
}